#!/usr/bin/env python3
"""Print and compare human-readable reports from experiment result joblib files."""

from __future__ import annotations

import argparse
import csv
import math
import numbers
from pathlib import Path
from typing import Any, Iterable

from joblib import load
import numpy as np


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Pretty-print classification or regression experiment results."
    )
    parser.add_argument(
        "joblib_files",
        type=Path,
        nargs="+",
        help="One or more result joblibs generated by the experiment pipeline.",
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("experiment_results_comparison.csv"),
        help="Comparison CSV output path (default: experiment_results_comparison.csv).",
    )
    parser.add_argument(
        "--decimals",
        type=int,
        default=4,
        help="Number of decimal places used for numeric metrics (default: 4).",
    )
    parser.add_argument(
        "--show-metadata",
        action="store_true",
        help="Also print the most relevant experiment configuration values.",
    )
    return parser.parse_args()


def format_value(value: Any, decimals: int) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, int):
        return f"{value:,}"
    if isinstance(value, float):
        if not math.isfinite(value):
            return str(value)
        return f"{value:.{decimals}f}"
    try:
        numeric = float(value)
    except (TypeError, ValueError):
        return str(value)
    return f"{numeric:.{decimals}f}"


def print_heading(title: str, character: str = "=") -> None:
    print(f"\n{title}")
    print(character * len(title))


def print_table(headers: Iterable[str], rows: Iterable[Iterable[Any]]) -> None:
    headers = [str(header) for header in headers]
    rows = [[str(cell) for cell in row] for row in rows]
    widths = [len(header) for header in headers]
    for row in rows:
        if len(row) != len(headers):
            raise ValueError("Every table row must have the same number of columns as the header.")
        widths = [max(width, len(cell)) for width, cell in zip(widths, row)]

    def render(row: Iterable[str]) -> str:
        return "  ".join(cell.ljust(width) for cell, width in zip(row, widths))

    print(render(headers))
    print(render("-" * width for width in widths))
    for row in rows:
        print(render(row))


def detect_task(metrics: dict[str, Any], metadata: dict[str, Any]) -> str:
    if metadata.get("is_regression") is True:
        return "regression"
    if metadata.get("is_regression") is False:
        return "classification"

    classification_keys = {
        "classification_report",
        "average_classification_report",
        "confusion_matrix",
        "aggregated_confusion_matrix",
        "accuracy",
        "auc",
    }
    regression_keys = {"MAE", "MSE", "RMSE", "R2", "average_metrics", "fold_weighted_metrics"}
    if classification_keys.intersection(metrics):
        return "classification"
    if regression_keys.intersection(metrics):
        return "regression"
    raise ValueError("Could not determine whether the joblib contains classification or regression results.")


def detect_scope(metrics: dict[str, Any]) -> str:
    """Classify results by the number of evaluated folds, not by storage schema."""
    folds = metrics.get("metrics_by_day")
    return "multi-fold" if isinstance(folds, list) and len(folds) > 1 else "single-fold"


def safe_name(value: Any) -> str:
    text = str(value).strip().lower()
    cleaned = "".join(character if character.isalnum() else "_" for character in text)
    return "_".join(part for part in cleaned.split("_") if part)


def scalar_value(value: Any) -> Any | None:
    if isinstance(value, numbers.Number):
        return value.item() if hasattr(value, "item") else value
    return None


def add_report_metrics(row: dict[str, Any], prefix: str, report: dict[str, Any]) -> None:
    for label, values in report.items():
        label_name = safe_name(label)
        if isinstance(values, dict):
            for metric, value in values.items():
                scalar = scalar_value(value)
                if scalar is not None:
                    row[f"{prefix}_{label_name}_{safe_name(metric)}"] = scalar
        else:
            scalar = scalar_value(values)
            if scalar is not None:
                row[f"{prefix}_{label_name}"] = scalar


def add_confusion_metrics(row: dict[str, Any], matrix: Any) -> None:
    if matrix is None:
        return
    values = matrix.tolist() if hasattr(matrix, "tolist") else matrix
    if not isinstance(values, list) or not values:
        return
    total = sum(float(value) for matrix_row in values for value in matrix_row)
    correct = sum(float(values[index][index]) for index in range(len(values)))
    row["global_accuracy"] = correct / total if total else None

    class_f1_values = []
    weighted_f1_sum = 0.0
    for actual, matrix_row in enumerate(values):
        row_total = sum(float(value) for value in matrix_row)
        true_positive = float(values[actual][actual])
        false_positive = sum(float(matrix_row[actual]) for matrix_row in values) - true_positive
        false_negative = row_total - true_positive
        precision_denominator = true_positive + false_positive
        recall_denominator = true_positive + false_negative
        precision = true_positive / precision_denominator if precision_denominator else 0.0
        recall = true_positive / recall_denominator if recall_denominator else 0.0
        f1_denominator = precision + recall
        f1 = 2.0 * precision * recall / f1_denominator if f1_denominator else 0.0
        class_name = safe_name(actual)
        row[f"global_class_{class_name}_precision"] = precision
        row[f"global_class_{class_name}_recall"] = recall
        row[f"global_class_{class_name}_f1"] = f1
        row[f"global_class_{class_name}_support"] = row_total
        class_f1_values.append(f1)
        weighted_f1_sum += f1 * row_total

        for predicted, value in enumerate(matrix_row):
            stem = f"confusion_actual_{actual}_predicted_{predicted}"
            row[f"{stem}_count"] = scalar_value(value)
            row[f"{stem}_percent"] = 100.0 * float(value) / row_total if row_total else None
    row["global_macro_f1"] = sum(class_f1_values) / len(class_f1_values)
    row["global_weighted_f1"] = weighted_f1_sum / total if total else None


def add_final_result_metrics(row: dict[str, Any], final_results: dict[str, Any]) -> None:
    """Flatten bootstrap-style ``(value, (lower, upper))`` results."""
    for metric, result in final_results.items():
        if metric == "per_class":
            continue
        if isinstance(result, (tuple, list)) and len(result) == 2:
            value, interval = result
            name = f"bootstrap_{safe_name(metric)}"
            row[name] = scalar_value(value)
            if isinstance(interval, (tuple, list)) and len(interval) == 2:
                row[f"{name}_ci_lower"] = scalar_value(interval[0])
                row[f"{name}_ci_upper"] = scalar_value(interval[1])

    for label, result in final_results.get("per_class", {}).items():
        if isinstance(result, (tuple, list)) and len(result) == 2:
            value, interval = result
            name = f"bootstrap_class_{safe_name(label)}_f1"
            row[name] = scalar_value(value)
            if isinstance(interval, (tuple, list)) and len(interval) == 2:
                row[f"{name}_ci_lower"] = scalar_value(interval[0])
                row[f"{name}_ci_upper"] = scalar_value(interval[1])


def add_fold_based_intervals(row: dict[str, Any], intervals: dict[str, Any]) -> None:
    for metric, values in intervals.items():
        if not isinstance(values, dict):
            continue
        name = f"fold_based_{safe_name(metric)}"
        key_map = {
            "mean": "mean",
            "lower_bound": "ci_lower",
            "upper_bound": "ci_upper",
            "margin_of_error": "margin_of_error",
            "lower": "ci_lower",
            "upper": "ci_upper",
        }
        for source_key, target_key in key_map.items():
            scalar = scalar_value(values.get(source_key))
            if scalar is not None:
                row[f"{name}_{target_key}"] = scalar


def add_nested_confidence_intervals(
    row: dict[str, Any],
    value: Any,
    path: tuple[str, ...] = (),
) -> None:
    """Capture additional explicitly named lower/upper bounds anywhere in metrics."""
    if isinstance(value, dict):
        lower_key = next((key for key in ("lower_bound", "lower") if key in value), None)
        upper_key = next((key for key in ("upper_bound", "upper") if key in value), None)
        if lower_key and upper_key:
            prefix = "source_ci_" + "_".join(safe_name(part) for part in path)
            row.setdefault(f"{prefix}_lower", scalar_value(value[lower_key]))
            row.setdefault(f"{prefix}_upper", scalar_value(value[upper_key]))
        for key, child in value.items():
            if key not in {"y_true", "y_pred", "residuals"}:
                add_nested_confidence_intervals(row, child, (*path, str(key)))
    elif isinstance(value, list):
        for index, child in enumerate(value, start=1):
            add_nested_confidence_intervals(row, child, (*path, f"fold_{index:02d}"))


def add_fold_metrics(row: dict[str, Any], task: str, folds: list[dict[str, Any]]) -> None:
    row["fold_count"] = len(folds)
    for index, fold in enumerate(folds, start=1):
        prefix = f"fold_{index:02d}"
        row[f"{prefix}_day"] = fold.get("day", "")
        if task == "classification":
            report = fold.get("classification_report", {})
            row[f"{prefix}_accuracy"] = scalar_value(fold.get("accuracy", report.get("accuracy")))
            row[f"{prefix}_auc"] = scalar_value(fold.get("auc"))
            row[f"{prefix}_macro_f1"] = scalar_value(
                report.get("macro avg", {}).get("f1-score")
            )
            row[f"{prefix}_support"] = scalar_value(
                report.get("weighted avg", {}).get("support")
            )
        else:
            for metric, value in fold.items():
                scalar = scalar_value(value)
                if scalar is not None:
                    row[f"{prefix}_{safe_name(metric)}"] = scalar
            threshold_fold = fold.get("regression_threshold_evaluation")
            if isinstance(threshold_fold, dict):
                for metric, value in threshold_fold.items():
                    scalar = scalar_value(value)
                    if scalar is not None:
                        row[f"{prefix}_threshold_{safe_name(metric)}"] = scalar


def build_comparison_row(result: dict[str, Any]) -> dict[str, Any]:
    path = result["path"]
    metrics = result["metrics"]
    metadata = result["metadata"]
    task = result["task"]
    scope = result["scope"]
    row: dict[str, Any] = {
        "file": str(path),
        "task": task,
        "scope": scope,
        "model_file": metadata.get("model_file", ""),
        "dataset": metadata.get("h5_path", ""),
        "test_date_start": metadata.get("test_date_start", ""),
        "test_date_end": metadata.get("test_date_end", ""),
        "random_state": metadata.get("random_state", ""),
    }

    add_final_result_metrics(row, metrics.get("final_results", {}))
    add_fold_based_intervals(row, metrics.get("confidence_intervals", {}))
    for key, value in metrics.items():
        if key not in {"final_results", "confidence_intervals"}:
            add_nested_confidence_intervals(row, value, (str(key),))

    if task == "classification":
        reports = (
            ("fold_weighted", metrics.get("fold_weighted_classification_report")),
            ("fold_average", metrics.get("average_classification_report")),
            ("single", metrics.get("classification_report")),
        )
        for prefix, report in reports:
            if isinstance(report, dict):
                add_report_metrics(row, prefix, report)
        for metric in ("accuracy", "auc"):
            scalar = scalar_value(metrics.get(metric))
            if scalar is not None:
                row[f"single_{metric}"] = scalar
        add_confusion_metrics(
            row,
            metrics.get("aggregated_confusion_matrix", metrics.get("confusion_matrix")),
        )
    else:
        for prefix, values in (
            ("fold_average", metrics.get("average_metrics")),
            ("fold_weighted", metrics.get("fold_weighted_metrics")),
            ("single", metrics),
        ):
            if isinstance(values, dict):
                for metric, value in values.items():
                    scalar = scalar_value(value)
                    if scalar is not None:
                        row[f"{prefix}_{safe_name(metric)}"] = scalar
        threshold_result = metrics.get("regression_threshold_evaluation")
        if isinstance(threshold_result, dict):
            row["regression_evaluation_threshold"] = scalar_value(
                threshold_result.get(
                    "threshold",
                    metadata.get("regression_evaluation_threshold"),
                )
            )
            row["threshold_support"] = scalar_value(threshold_result.get("SUPPORT"))
            threshold_final: dict[str, Any] = {}
            if isinstance(threshold_result.get("final_results"), dict):
                threshold_final = threshold_result["final_results"]
            for metric, result_value in threshold_final.items():
                if (
                    isinstance(result_value, (tuple, list))
                    and len(result_value) == 2
                ):
                    value, interval = result_value
                    name = f"threshold_bootstrap_{safe_name(metric)}"
                    row[name] = scalar_value(value)
                    if isinstance(interval, (tuple, list)) and len(interval) == 2:
                        row[f"{name}_ci_lower"] = scalar_value(interval[0])
                        row[f"{name}_ci_upper"] = scalar_value(interval[1])
            for prefix, values in (
                ("threshold_fold_average", threshold_result.get("average_metrics")),
                ("threshold_fold_weighted", threshold_result.get("fold_weighted_metrics")),
            ):
                if isinstance(values, dict):
                    for metric, value in values.items():
                        scalar = scalar_value(value)
                        if scalar is not None:
                            row[f"{prefix}_{safe_name(metric)}"] = scalar

    folds = metrics.get("metrics_by_day", [])
    if isinstance(folds, list) and folds:
        add_fold_metrics(row, task, folds)
        if task == "classification":
            auc_values = [
                scalar_value(fold.get("auc"))
                for fold in folds
                if scalar_value(fold.get("auc")) is not None
            ]
            if auc_values:
                row["global_auc"] = sum(auc_values) / len(auc_values)
    else:
        row["fold_count"] = 1
        if task == "classification" and scalar_value(metrics.get("auc")) is not None:
            row["global_auc"] = scalar_value(metrics.get("auc"))
    return row


def first_available(row: dict[str, Any], columns: Iterable[str]) -> Any | None:
    for column in columns:
        value = scalar_value(row.get(column))
        if value is not None:
            return value
    return None


def add_canonical_performance_metrics(row: dict[str, Any], task: str) -> None:
    """Select one consistent point estimate for each baseline comparison metric."""
    if task == "classification":
        aliases = {
            "accuracy": ("global_accuracy", "bootstrap_accuracy", "single_accuracy"),
            "auc": ("global_auc", "bootstrap_auc", "single_auc"),
            "macro_f1": ("global_macro_f1",),
            "weighted_f1": ("global_weighted_f1", "bootstrap_f1"),
        }
        for name, columns in aliases.items():
            value = first_available(row, columns)
            if value is not None:
                row[f"performance_{name}"] = value

        prefix = "global_class_"
        suffixes = ("_precision", "_recall", "_f1")
        for column, value in list(row.items()):
            if column.startswith(prefix) and column.endswith(suffixes):
                row[f"performance_{column[len('global_'):]}"] = value
    else:
        for metric in ("mae", "rmse", "mse", "r2"):
            value = first_available(
                row,
                (
                    f"bootstrap_{metric}",
                    f"single_{metric}",
                    f"fold_weighted_{metric}",
                ),
            )
            if value is not None:
                row[f"performance_{metric}"] = value
            threshold_value = first_available(
                row,
                (
                    f"threshold_bootstrap_{metric}",
                    f"threshold_single_{metric}",
                    f"threshold_fold_weighted_{metric}",
                ),
            )
            if threshold_value is not None:
                row[f"performance_threshold_{metric}"] = threshold_value


def add_baseline_improvements(rows: list[dict[str, Any]], task: str) -> list[str]:
    """Add direction-aware absolute and relative improvements to every row."""
    baseline = rows[0]
    baseline_file = baseline["file"]
    performance_columns = sorted(
        column for column in baseline if column.startswith("performance_")
    )
    lower_is_better = {
        "performance_mae", "performance_rmse", "performance_mse",
        "performance_threshold_mae", "performance_threshold_rmse",
        "performance_threshold_mse",
    }
    warnings = []

    for row_index, row in enumerate(rows):
        row["baseline_file"] = baseline_file
        for column in performance_columns:
            metric_name = column[len("performance_"):]
            absolute_column = f"improvement_{metric_name}_absolute"
            relative_column = f"improvement_{metric_name}_relative"
            if row_index == 0:
                row[absolute_column] = 0.0
                row[relative_column] = 0.0
                continue

            baseline_value = scalar_value(baseline.get(column))
            experiment_value = scalar_value(row.get(column))
            if baseline_value is None or experiment_value is None:
                row[absolute_column] = None
                row[relative_column] = None
                warnings.append(
                    f"{row['file']}: cannot compare {metric_name}; value is unavailable."
                )
                continue

            direction = -1.0 if column in lower_is_better else 1.0
            difference = direction * (experiment_value - baseline_value)
            row[absolute_column] = difference
            if baseline_value == 0:
                row[relative_column] = None
                warnings.append(
                    f"{row['file']}: relative {metric_name} improvement is undefined "
                    "because the baseline value is zero."
                )
            else:
                row[relative_column] = difference / abs(baseline_value)
    return warnings


def write_comparison_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    identity = [
        "file",
        "baseline_file",
        "task",
        "scope",
        "model_file",
        "dataset",
        "test_date_start",
        "test_date_end",
        "random_state",
        "fold_count",
    ]
    all_columns = set().union(*(row.keys() for row in rows))
    fieldnames = [key for key in identity if key in all_columns]
    fieldnames.extend(sorted(all_columns.difference(fieldnames)))
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def load_result(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise ValueError(f"Result file not found: {path}")
    try:
        payload = load(path)
    except Exception as exc:
        raise ValueError(f"Could not load {path}: {exc}") from exc
    if not isinstance(payload, dict):
        raise ValueError(f"{path}: expected the joblib to contain a dictionary.")
    metrics = payload.get("metrics", payload)
    metadata = payload.get("metadata", {})
    if not isinstance(metrics, dict):
        raise ValueError(f"{path}: expected metrics to be a dictionary.")
    task = detect_task(metrics, metadata)
    return {
        "path": path,
        "metrics": metrics,
        "metadata": metadata,
        "task": task,
        "scope": detect_scope(metrics),
    }


def validate_compatible(results: list[dict[str, Any]]) -> None:
    kinds = {(result["task"], result["scope"]) for result in results}
    if len(kinds) == 1:
        if results[0]["task"] == "regression":
            thresholds = []
            for result in results:
                threshold_result = result["metrics"].get(
                    "regression_threshold_evaluation"
                )
                thresholds.append(
                    threshold_result.get("threshold")
                    if isinstance(threshold_result, dict) else None
                )
            if any(value is not None for value in thresholds) and (
                any(value is None for value in thresholds)
                or len({float(value) for value in thresholds if value is not None}) != 1
            ):
                raise ValueError(
                    "Incompatible result files: regression evaluation thresholds "
                    "must all be absent or have the same value."
                )
        return
    lines = ["Incompatible result files:"]
    for result in results:
        lines.append(f"  {result['path']}: {result['task']} / {result['scope']}")
    raise ValueError("\n".join(lines))


def report_rows(report: dict[str, Any], decimals: int) -> list[list[str]]:
    rows = []
    for label, values in report.items():
        if label == "accuracy" or not isinstance(values, dict):
            continue
        rows.append(
            [
                label,
                format_value(values.get("precision"), decimals),
                format_value(values.get("recall"), decimals),
                format_value(values.get("f1-score"), decimals),
                format_value(values.get("support"), decimals),
            ]
        )
    if "accuracy" in report:
        rows.append(["accuracy", "-", "-", format_value(report["accuracy"], decimals), "-"])
    return rows


def print_confusion_matrix(matrix: Any, decimals: int) -> None:
    if matrix is None:
        return
    rows = matrix.tolist() if hasattr(matrix, "tolist") else matrix
    if not isinstance(rows, list) or not rows:
        return
    class_count = len(rows)
    print_heading("Confusion matrix", "-")
    headers = ["actual \\ predicted"] + [f"class {index}" for index in range(class_count)]
    print_table(
        headers,
        [[f"class {index}", *[str(int(value)) for value in row]] for index, row in enumerate(rows)],
    )

    percentage_rows = []
    for index, row in enumerate(rows):
        row_total = sum(float(value) for value in row)
        percentages = [
            f"{(100.0 * float(value) / row_total):.{decimals}f}%" if row_total else "-"
            for value in row
        ]
        percentage_rows.append([f"class {index}", *percentages])

    print_heading("Confusion matrix percentages (normalized by actual class)", "-")
    print_table(headers, percentage_rows)


def complete_pooled_classification_results(metrics: dict[str, Any]) -> dict[str, Any]:
    """Add pooled precision/recall results, including for legacy Joblib files."""
    final_results = dict(metrics.get("final_results", {}))
    daily = metrics.get("metrics_by_day", [])
    cms = [np.asarray(entry["confusion_matrix"]) for entry in daily if "confusion_matrix" in entry]
    if not cms:
        return final_results
    global_cm = np.sum(cms, axis=0)

    def class_precision(cm, cls):
        tp = cm[cls, cls]
        denominator = cm[:, cls].sum()
        return float(tp / denominator) if denominator else 0.0

    def class_recall(cm, cls):
        tp = cm[cls, cls]
        denominator = cm[cls, :].sum()
        return float(tp / denominator) if denominator else 0.0

    def class_f1(cm, cls):
        tp = cm[cls, cls]
        fp = cm[:, cls].sum() - tp
        fn = cm[cls, :].sum() - tp
        denominator = 2 * tp + fp + fn
        return float(2 * tp / denominator) if denominator else 0.0

    def support_weighted(cm, metric_func):
        supports = cm.sum(axis=1)
        total = supports.sum()
        return float(sum(metric_func(cm, cls) * supports[cls]
                         for cls in range(cm.shape[0])) / total) if total else 0.0

    def bootstrap(metric_func):
        rng = np.random.RandomState(42)
        values = []
        for _ in range(1000):
            indices = rng.randint(0, len(cms), size=len(cms))
            sampled_cm = np.sum([cms[index] for index in indices], axis=0)
            values.append(metric_func(sampled_cm))
        lower, upper = np.percentile(values, [2.5, 97.5])
        return float(lower), float(upper)

    weighted = {
        "precision": lambda cm: support_weighted(cm, class_precision),
        "recall": lambda cm: support_weighted(cm, class_recall),
    }
    for name, metric_func in weighted.items():
        final_results.setdefault(name, (metric_func(global_cm), bootstrap(metric_func)))

    for result_name, metric_func in (
        ("per_class", class_f1),
        ("per_class_precision", class_precision),
        ("per_class_recall", class_recall),
    ):
        class_results = dict(final_results.get(result_name, {}))
        for cls in range(global_cm.shape[0]):
            def class_func(cm, cls=cls, func=metric_func):
                return func(cm, cls)
            class_results.setdefault(str(cls), (class_func(global_cm), bootstrap(class_func)))
        final_results[result_name] = class_results
    return final_results


def print_final_results(
    final_results: dict[str, Any],
    decimals: int,
    heading: str = "Global results and 95% confidence intervals",
) -> None:
    if not final_results:
        return
    rows = []
    for name, result in final_results.items():
        if name.startswith("per_class") or not isinstance(result, (tuple, list)) or len(result) != 2:
            continue
        value, interval = result
        lower, upper = interval if isinstance(interval, (tuple, list)) and len(interval) == 2 else (None, None)
        rows.append([name, format_value(value, decimals), format_value(lower, decimals),
                     format_value(upper, decimals)])
    if rows:
        print_heading(heading, "-")
        print_table(["metric", "value", "CI lower", "CI upper"], rows)
        if final_results.get("per_class"):
            print("Note: F1, precision, recall and accuracy use the confusion matrix formed by "
                  "summing all fold confusion matrices. F1, precision and recall are "
                  "class-support-weighted. Their intervals bootstrap complete folds with "
                  "replacement, sum the sampled matrices, and recalculate each metric. "
                  "AUC is the mean fold AUC and bootstraps the fold AUC values.")

    per_class_results = {
        "precision": final_results.get("per_class_precision", {}),
        "recall": final_results.get("per_class_recall", {}),
        "F1": final_results.get("per_class", {}),
    }
    labels = sorted(set().union(*(result.keys() for result in per_class_results.values())))
    if labels:
        rows = []
        for label in labels:
            for metric_name, results in per_class_results.items():
                if label in results:
                    value, interval = results[label]
                    rows.append([label, metric_name, format_value(value, decimals),
                                 format_value(interval[0], decimals), format_value(interval[1], decimals)])
        print_heading("Per-class metrics and 95% confidence intervals", "-")
        print_table(["class", "metric", "value", "CI lower", "CI upper"], rows)
        print("Note: Point estimates use the summed fold confusion matrix. Each interval "
              "bootstraps complete folds with replacement, sums the sampled matrices, "
              "and recalculates the class metric.")


