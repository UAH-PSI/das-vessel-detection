def console_performance_columns(
    rows: list[dict[str, Any]],
    task: str,
) -> list[str]:
    """Return the intentionally compact metric set used only in console output."""
    if task == "classification":
        columns = [
            "performance_accuracy",
            "performance_macro_f1",
            "performance_weighted_f1",
        ]
        class_columns = sorted({
            column
            for row in rows
            for column in row
            if column.startswith("performance_class_")
            and column.endswith(("_precision", "_recall"))
        })
        columns.extend(class_columns)
    else:
        columns = ["performance_mae", "performance_rmse"]
        if any("performance_threshold_mae" in row for row in rows):
            columns.extend([
                "performance_threshold_mae",
                "performance_threshold_rmse",
            ])
    return [column for column in columns if column in rows[0]]


def performance_label(column: str) -> str:
    name = column.removeprefix("performance_")
    labels = {
        "accuracy": "Accuracy",
        "macro_f1": "Macro F1",
        "weighted_f1": "Weighted F1",
        "mae": "MAE",
        "rmse": "RMSE",
        "threshold_mae": "Threshold MAE",
        "threshold_rmse": "Threshold RMSE",
    }
    if name in labels:
        return labels[name]
    if name.startswith("class_"):
        parts = name.split("_")
        if len(parts) >= 3:
            return f"Class {parts[1]} {' '.join(parts[2:]).title()}"
    return name.replace("_", " ").title()


def format_improvement(value: Any, decimals: int, percentage: bool = False) -> str:
    scalar = scalar_value(value)
    if scalar is None or not math.isfinite(float(scalar)):
        return "-"
    if scalar == 0:
        return f"{0:.{decimals}f}%" if percentage else f"{0:.{decimals}f}"
    multiplier = 100.0 if percentage else 1.0
    suffix = "%" if percentage else ""
    return f"{float(scalar) * multiplier:+.{decimals}f}{suffix}"


def print_performance_comparison(
    results: list[dict[str, Any]],
    rows: list[dict[str, Any]],
    decimals: int,
) -> None:
    """Print selected metrics for any number of candidates against row zero."""
    columns = console_performance_columns(rows, results[0]["task"])
    print_heading("Main performance comparison")
    print("Experiment files:")
    for index, result in enumerate(results, start=1):
        role = "baseline" if index == 1 else "candidate"
        print(f"  {index} ({role}): {result['path'].resolve()}")

    table_rows = []
    for index, row in enumerate(rows, start=1):
        for column in columns:
            name = column.removeprefix("performance_")
            table_rows.append([
                f"{index}{' (baseline)' if index == 1 else ''}",
                performance_label(column),
                format_value(row.get(column), decimals),
                format_improvement(
                    row.get(f"improvement_{name}_absolute"),
                    decimals,
                ),
                format_improvement(
                    row.get(f"improvement_{name}_relative"),
                    decimals,
                    percentage=True,
                ),
            ])
    print_table(
        ["experiment", "metric", "value", "absolute improvement", "relative improvement"],
        table_rows,
    )

    for index, row in enumerate(rows[1:], start=2):
        print_heading(f"Differences for experiment {index}", "-")
        difference_rows = []
        for column in columns:
            name = column.removeprefix("performance_")
            absolute = scalar_value(row.get(f"improvement_{name}_absolute"))
            if absolute is None or not math.isfinite(float(absolute)):
                status = "unavailable"
            elif absolute > 0:
                status = "improved"
            elif absolute < 0:
                status = "degraded"
            else:
                status = "unchanged"
            difference_rows.append([
                performance_label(column),
                format_value(row.get(column), decimals),
                format_improvement(absolute, decimals),
                format_improvement(
                    row.get(f"improvement_{name}_relative"),
                    decimals,
                    percentage=True,
                ),
                status,
            ])
        print_table(
            ["metric", "value", "absolute improvement", "relative improvement", "result"],
            difference_rows,
        )


def main() -> None:
    args = parse_args()
    if args.decimals < 0:
        raise SystemExit("--decimals must be zero or greater.")
    try:
        results = [load_result(path) for path in args.joblib_files]
        validate_compatible(results)
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc

    comparison_rows = [build_comparison_row(result) for result in results]
    for row in comparison_rows:
        add_canonical_performance_metrics(row, results[0]["task"])
    improvement_warnings = add_baseline_improvements(
        comparison_rows,
        results[0]["task"],
    )
    write_comparison_csv(args.csv, comparison_rows)

    if len(results) == 1:
        print_complete_result(
            results[0],
            args.decimals,
            args.show_metadata,
            "Experiment results",
        )
    else:
        print_heading("Experiment comparison")
        print(f"Files: {len(results)}")
        print(f"Baseline: {results[0]['path']}")
        print(f"Task: {results[0]['task']}")
        print(f"Scope: {results[0]['scope']}")
        for index, result in enumerate(results, start=1):
            role = "Baseline" if index == 1 else "Candidate"
            print_complete_result(
                result,
                args.decimals,
                args.show_metadata,
                f"Experiment {index} — {role}",
            )
        print_performance_comparison(
            results,
            comparison_rows,
            args.decimals,
        )
    for warning in dict.fromkeys(improvement_warnings):
        print(f"Warning: {warning}")
    print(f"\nComparison CSV: {args.csv.resolve()}")


if __name__ == "__main__":
    main()
